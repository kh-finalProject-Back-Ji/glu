CHECK (LOGIN_TYPE IN ('LOCAL','OAUTH'));

ALTER TABLE MEMBER ADD CONSTRAINT CK_MEMBER_STATUS
CHECK (STATUS IN ('ACTIVE','BLOCKED','WITHDRAW'));

ALTER TABLE MEMBER ADD CONSTRAINT CK_MEMBER_ROLE
