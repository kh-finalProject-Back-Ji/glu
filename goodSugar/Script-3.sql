CREATE TABLE MEMBER (
  MEMBER_ID       NUMBER(20) PRIMARY KEY,

  EMAIL           VARCHAR2(100) NOT NULL,
  NICKNAME        VARCHAR2(50)  NOT NULL,

  LOGIN_TYPE      VARCHAR2(20) DEFAULT 'LOCAL' NOT NULL, -- LOCAL / OAUTH
  PASSWORD_HASH   VARCHAR2(200),

  OAUTH_PROVIDER  VARCHAR2(20),
  OAUTH_UID       VARCHAR2(100),

  NAME            VARCHAR2(50),
  GENDER          VARCHAR2(10),
  PROFILE_IMG     VARCHAR2(400),
  MEMBER_BIRTH    DATE,

  CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATE_AT       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  LAST_LOGIN_AT   TIMESTAMP,
  WITHDRAW_AT     TIMESTAMP,

  STATUS          VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL, -- ACTIVE / BLOCKED / WITHDRAW
  ROLE            VARCHAR2(20) DEFAULT 'USER' NOT NULL     -- USER / ADMIN
);

