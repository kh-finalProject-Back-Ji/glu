CREATE INDEX IDX_MEMBER_STATUS ON MEMBER(STATUS);



CREATE TABLE EMAIL_VERIFY (
  VERIFY_ID    NUMBER(20) PRIMARY KEY,
  MEMBER_ID    NUMBER(20),
  EMAIL        VARCHAR2(100) NOT NULL,
  VERIFY_CODE  VARCHAR2(20)  NOT NULL,
  EXPIRED_AT   TIMESTAMP     NOT NULL,
  VERIFIED_AT  TIMESTAMP
);

ALTER TABLE EMAIL_VERIFY
ADD CONSTRAINT FK_EMAIL_VERIFY_MEMBER
FOREIGN KEY (MEMBER_ID) REFERENCES MEMBER(MEMBER_ID);

CREATE INDEX IDX_EMAIL_VERIFY_EMAIL ON EMAIL_VERIFY(EMAIL);
CREATE INDEX IDX_EMAIL_VERIFY_MEMBER ON EMAIL_VERIFY(MEMBER_ID);
CREATE INDEX IDX_EMAIL_VERIFY_EMAIL_CODE ON EMAIL_VERIFY(EMAIL, VERIFY_CODE);
CREATE INDEX IDX_EMAIL_VERIFY_EXPIRED ON EMAIL_VERIFY(EXPIRED_AT);



CREATE TABLE GLUCOSE_RECORD (
